import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import * as prettier from 'prettier'

// Ship optional runtime data in static-host-safe pieces, never in the initial app bundle.
const require = createRequire(import.meta.url)
const version = '1.30.0'
const prefix = `/models/beat-this/runtime-${version}`
const output = join(process.cwd(), 'public', prefix)
await mkdir(output, { recursive: true })
async function writeChanged(path, value) {
  const bytes = Buffer.from(value)
  const previous = await readFile(path).catch(() => null)
  if (!previous?.equals(bytes)) await writeFile(path, bytes)
}
const wasm = await readFile(require.resolve('onnxruntime-web/ort-wasm-simd-threaded.jsep.wasm'))
const parts = []
const chunkSize = 8 * 1024 * 1024
for (let offset = 0; offset < wasm.length; offset += chunkSize) {
  const bytes = wasm.subarray(offset, offset + chunkSize)
  const name = `runtime-${parts.length}.bin`
  await writeChanged(join(output, name), bytes)
  parts.push({
    url: `${prefix}/${name}`,
    bytes: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex'),
  })
}
const mjs = 'ort-wasm-simd-threaded.jsep.mjs'
await writeChanged(join(output, mjs), await readFile(require.resolve(`onnxruntime-web/${mjs}`)))
const target = join(process.cwd(), 'src/generated/beat-this-runtime.ts')
await mkdir(dirname(target), { recursive: true })
await writeChanged(
  target,
  await prettier.format(
    `// Generated by scripts/prepare-beat-runtime.mjs from pinned onnxruntime-web.\nexport const BEAT_THIS_RUNTIME = ${JSON.stringify({ version: `ort-${version}`, parts, bytes: wasm.length, mjs: `${prefix}/${mjs}` }, null, 2)} as const\n`,
    { ...(await prettier.resolveConfig(target)), parser: 'typescript' },
  ),
)
